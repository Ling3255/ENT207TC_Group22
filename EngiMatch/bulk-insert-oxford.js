async function main() {
  console.log(`Bulk inserting ${oxfordProgrammes.length} Oxford programmes...\n`);

  let created = 0;
  let skipped = 0;

  for (const data of oxfordProgrammes) {
    const existing = await prisma.programme.findFirst({
      where: {
        university_id: OXFORD_ID,
        slug: data.slug,
      },
    });

    if (existing) {
      console.log(`  ⚠ Skipped (exists): ${data.programme_name}`);
      skipped++;
      continue;
    }

    const { study_type, ...createData } = data;

    await prisma.programme.create({
      data: {
        ...createData,
        university_id: OXFORD_ID,
      },
    });

    console.log(`  ✅ Created [${study_type}]: ${data.programme_name}`);
    created++;
  }

  console.log(`\nDone. Created: ${created}, Skipped: ${skipped}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
