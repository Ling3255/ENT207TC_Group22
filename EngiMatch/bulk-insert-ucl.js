async function main() {
  console.log(`Bulk inserting ${uclProgrammes.length} UCL programmes...\n`);

  let created = 0;
  let skipped = 0;

  for (const data of uclProgrammes) {
    const existing = await prisma.programme.findFirst({
      where: {
        university_id: UCL_ID,
        slug: data.slug,
      },
    });

    if (existing) {
      console.log(`  ⚠ Skipped (exists): ${data.programme_name}`);
      skipped++;
      continue;
    }

    await prisma.programme.create({
      data: {
        ...data,
        university_id: UCL_ID,
      },
    });

    console.log(`  ✅ Created: ${data.programme_name}`);
    created++;
  }

  console.log(`\nDone. Created: ${created}, Skipped: ${skipped}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
